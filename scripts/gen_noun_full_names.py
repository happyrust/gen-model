#!/usr/bin/env python3
"""从 `output/noun_layout.json` 生成短名词 → 名词全词的两份产物。

    resource/dict/noun_full_names.json   gen-model 与 plant-ui `aios_core` 内嵌的表
    resource/dict/noun_full_names.surql  plant-ui `common.surql` 里那段 DEFINE PARAM


E3D 的默认全名（`FLNM`）写的是名词**全词**（`BRANCH` / `EQUIPMENT` / `TMPLATE`），
不是库里存的四五字短名词（`BRAN` / `EQUI` / `TMPL`）。活 E3D 导出的
`noun_layout.json` 每条同时带 `short`（库形态）与 `noun`（全词），这里把两者不同
的那些抽成一张小表随二进制发布——全表 4.3MB 太大，短名词与全词相同的那 1418 条
也没有查表的必要（查不到就退回短名词，正是对的答案）。

用法（仓根）：

    python scripts/gen_noun_full_names.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "output" / "noun_layout.json"
TARGET = ROOT / "resource" / "dict" / "noun_full_names.json"
SURQL_TARGET = ROOT / "resource" / "dict" / "noun_full_names.surql"

SURQL_HEADER = """-- AUTO-GENERATED by gen-model `scripts/gen_noun_full_names.py` -- DO NOT EDIT BY HAND
-- 短名词 → 名词全词，只收两者不同的那些；查不到就退回短名词。
-- 与 gen-model / aios_core 内嵌的 `noun_full_names.json` 同源同内容。
-- 定成 PARAM 而不是函数体里的字面量：函数体里的对象每次调用都要重建一遍，
-- 而 `fn::default_full_name` 是逐行调的。
-- `IF EXISTS` 不能省：裸 `REMOVE PARAM` 在还没定义过它的库上报 `PaNotFound`，
-- 整份 common.surql 就停在这一句（实测 SurrealDB 2.1.4 fork）。
REMOVE PARAM IF EXISTS $NOUN_FULL_NAMES;
DEFINE PARAM $NOUN_FULL_NAMES VALUE {
"""

SURQL_FOOTER = """};
"""


def write_surql(table: dict[str, str]) -> None:
    """一行装满 100 列再换行：这段要原样贴进 plant-ui 三份 `common.surql`，
    一条一行的话每份多出 500 行淹掉手写的部分。"""
    lines, row = [SURQL_HEADER], "   "
    for short, full in sorted(table.items()):
        entry = f' "{short}": "{full}",'
        if len(row) + len(entry) > 100:
            lines.append(row + "\n")
            row = "   "
        row += entry
    lines.append(row + "\n")
    lines.append(SURQL_FOOTER)
    SURQL_TARGET.write_text("".join(lines), encoding="utf-8")


def main() -> None:
    layout = json.loads(SOURCE.read_text(encoding="utf-8"))
    table = {}
    for entry in layout:
        short = entry["short"].strip()
        full = entry["noun"].strip()
        # 空全词是字典里没登记全名的内部名词（LTEA/EPLA…，visible=false），
        # 收进表里会把它们的显示名擦成空串。
        if not short or not full or short == full:
            continue
        if short in table and table[short] != full:
            raise SystemExit(f"short noun {short} maps to both {table[short]} and {full}")
        table[short] = full
    TARGET.write_text(
        json.dumps(dict(sorted(table.items())), ensure_ascii=False, indent=0) + "\n",
        encoding="utf-8",
    )
    write_surql(table)
    print(f"{len(table)} nouns -> {TARGET.relative_to(ROOT)}, {SURQL_TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
