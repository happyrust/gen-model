param(
    [Parameter(Mandatory = $true)]
    [string]$PmlLibRoot
)

$ErrorActionPreference = 'Stop'
$target = Join-Path $PmlLibRoot 'common\objects\pmlcommandmanager.pmlobj'
if (-not (Test-Path -LiteralPath $target)) {
    throw "PML command manager not found: $target"
}

$text = [IO.File]::ReadAllText($target)
$originalText = $text
$globalMarker = '-- AIOS AMS: initialise the steelwork global before command refresh registration.'
$orderMarker = '-- AIOS AMS: all support commands now exist; generated refresh callbacks may register.'

$newline = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
if (-not $text.Contains($globalMarker)) {
    $needle = "define method .loadDesignSteelworkCommands()${newline}${newline}  -- Load list of commands"
    if (-not $text.Contains($needle)) {
        throw "Steelwork command loader signature changed; no file was modified: $target"
    }
    $replacement = @(
        'define method .loadDesignSteelworkCommands()'
        ''
        "  $globalMarker"
        '  if (undefined(!!steelworkgsettings)) then'
        '    !!comDefineGlobal(object STEELWORKOSETTINGS())'
        '  endif'
        ''
        '  -- Load list of commands'
    ) -join $newline
    $text = $text.Replace($needle, $replacement)
}

if (-not $text.Contains($orderMarker)) {
    $methodStart = $text.IndexOf('define method .loadDesignSteelworkCommands()')
    $methodEnd = $text.IndexOf("${newline}endmethod", $methodStart)
    if ($methodStart -lt 0 -or $methodEnd -lt 0) {
        throw "Steelwork command loader boundary changed: $target"
    }
    $registerStart = $text.IndexOf('  !!registerAutogeneratedSteelworkCommands()', $methodStart)
    $registerEnd = $text.IndexOf("${newline}  endhandle", $registerStart)
    if ($registerStart -lt 0 -or $registerEnd -lt 0 -or $registerEnd -gt $methodEnd) {
        throw "Generated Steelwork register block changed: $target"
    }
    $registerEnd += "${newline}  endhandle".Length
    $registerBlock = $text.Substring($registerStart, $registerEnd - $registerStart)
    $text = $text.Remove($registerStart, $registerEnd - $registerStart)

    $methodEnd = $text.IndexOf("${newline}endmethod", $methodStart)
    $loadCall = '  !this.loadCommands(!commands)'
    $loadAt = $text.LastIndexOf($loadCall, $methodEnd, $methodEnd - $methodStart)
    if ($loadAt -lt $methodStart) {
        throw "Steelwork support command load call changed: $target"
    }
    $insertAt = $loadAt + $loadCall.Length
    $orderedRegister = "${newline}${newline}  $orderMarker${newline}$registerBlock"
    $text = $text.Insert($insertAt, $orderedRegister)
}

$backup = "$target.aios-original"
if (-not (Test-Path -LiteralPath $backup)) {
    [IO.File]::WriteAllText($backup, $originalText, [Text.Encoding]::UTF8)
}
if ($text -ne $originalText) {
    [IO.File]::WriteAllText($target, $text, [Text.Encoding]::UTF8)
}

$verify = [IO.File]::ReadAllText($target)
if (-not $verify.Contains($globalMarker) -or
    -not $verify.Contains('!!comDefineGlobal(object STEELWORKOSETTINGS())') -or
    -not $verify.Contains($orderMarker)) {
    throw "Steelwork global guard verification failed: $target"
}
Write-Host "[PML] Steelwork globals and registration order verified: $target"
